import { types } from 'pg';

/**
 * По умолчанию драйвер pg возвращает колонки NUMERIC/DECIMAL как строки
 * (во избежание потери точности). Для этого демонстрационного проекта
 * удобнее получать числа сразу (упрощает фронтенд и DTO-валидацию),
 * поэтому глобально включаем парсинг NUMERIC (OID 1700) в JS number.
 * Должно быть импортировано (для побочного эффекта) до установления
 * соединения с БД — см. main.ts.
 */
types.setTypeParser(1700, (value: string) => parseFloat(value));
